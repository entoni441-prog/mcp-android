/**
 * NEXUS Host — read-only window inventory (tool `list_windows`).
 *
 * Mechanism: signed %SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe with a FIXED script
 * (nothing from the request is interpolated; the only variable is our own temp-file path).
 * Uses only Get-Process / Where-Object / Select-Object / ConvertTo-Json / Out-File — all usable in
 * Constrained Language Mode (which Smart App Control enforces), no .NET/Win32 calls.
 * Output goes to a UTF-8 file instead of stdout, so Cyrillic/accented titles survive the OEM console codepage.
 *
 * Privacy: window titles may contain personal data (document names, mail subjects, URLs).
 * Default response = process name + pid only; titles only with includeTitles=true.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
import {runUiaReal} from './gui.mjs';

const MAX_WINDOWS = 100;
const MAX_TITLE = 200;
const TIMEOUT_MS = 15_000;

export const LIST_WINDOWS_TOOL = {
  name: 'list_windows',
  description: 'List top-level windows open on the owner\'s Windows desktop (read-only). Returns pid and process name; window titles only when includeTitles=true (titles may contain personal data).',
  inputSchema: {type: 'object', properties: {includeTitles: {type: 'boolean', description: 'Also return window titles. Default false.'}}, additionalProperties: false},
  annotations: {readOnlyHint: true},
};

export function validateListWindows(args) {
  if (args === null || typeof args !== 'object' || Array.isArray(args)) throw Error('invalid_args');
  for (const k of Object.keys(args)) if (k !== 'includeTitles') throw Error('invalid_args');
  if (Object.hasOwn(args, 'includeTitles') && typeof args.includeTitles !== 'boolean') throw Error('invalid_args');
  return args.includeTitles === true;
}

/** Fixed script; `outFile` is generated by us (random hex name in our own folder), quoted for PowerShell. */
export function buildScript(outFile, includeTitles) {
  const lit = "'" + String(outFile).replace(/'/g, "''") + "'";
  const fields = includeTitles ? 'Id,ProcessName,MainWindowTitle' : 'Id,ProcessName';
  return [
    "$ErrorActionPreference = 'Stop'",
    `$w = @(Get-Process | Where-Object { $_.MainWindowTitle -ne '' } | Select-Object ${fields})`,
    `ConvertTo-Json -InputObject $w -Compress | Out-File -LiteralPath ${lit} -Encoding utf8`,
  ].join('; ');
}

export function parseOutput(raw, includeTitles) {
  const text = String(raw).replace(/^﻿/, '').trim();
  if (!text) return [];
  let data;
  try { data = JSON.parse(text); } catch { throw Error('powershell_bad_output'); }
  if (!Array.isArray(data)) data = [data];
  return data.filter(x => x && Number.isInteger(x.Id) && typeof x.ProcessName === 'string').map(x => {
    const item = {pid: x.Id, process: x.ProcessName.slice(0, 100)};
    if (includeTitles) item.title = typeof x.MainWindowTitle === 'string' ? x.MainWindowTitle.slice(0, MAX_TITLE) : '';
    return item;
  });
}

function runPowerShellReal(script, {systemRoot}) {
  if (typeof systemRoot !== 'string' || !/^[a-zA-Z]:\\/.test(systemRoot)) throw Error('invalid_windows_system_root');
  const exe = path.win32.join(systemRoot, 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  return new Promise((resolve, reject) => {
    const p = spawn(exe, ['-NoProfile', '-NonInteractive', '-Command', script], {stdio: ['ignore', 'ignore', 'pipe'], windowsHide: true});
    let err = '';
    const timer = setTimeout(() => { p.kill(); reject(Error('powershell_timeout')); }, TIMEOUT_MS);
    p.stderr.on('data', c => { if (err.length < 2000) err += c; });
    p.once('error', () => { clearTimeout(timer); reject(Error('powershell_launch_failed')); });
    p.once('exit', code => { clearTimeout(timer); code === 0 ? resolve() : reject(Object.assign(Error('powershell_failed'), {detail: err.slice(0, 500)})); });
  });
}

export async function listWindows(args, {platform = process.platform, tmpDir, systemRoot = process.env.SystemRoot, runPowerShell = runPowerShellReal, runUia = null} = {}) {
  const includeTitles = validateListWindows(args);
  if (platform !== 'win32') throw Error('windows_only');
  if (typeof tmpDir !== 'string' || !path.isAbsolute(tmpDir)) throw Error('invalid_tmp_dir');
  fs.mkdirSync(tmpDir, {recursive: true});
  const outFile = path.join(tmpDir, 'windows-' + crypto.randomBytes(8).toString('hex') + '.json');
  try {
    await runPowerShell(buildScript(outFile, includeTitles), {systemRoot, outFile});
    if (!fs.existsSync(outFile)) throw Error('powershell_no_output');
    let all = parseOutput(fs.readFileSync(outFile, 'utf8'), includeTitles);
    // NX-052-19: Explorer is a shared shell process; MainWindowTitle can be empty
    // while CabinetWClass windows exist. UIA already enumerates those for window_info.
    const enumerate = runUia || (runPowerShell === runPowerShellReal ? runUiaReal : null);
    if (enumerate) {
      try {
        const snap = await enumerate({mode: 'apps', name: 'explorer'}, {tmpDir, systemRoot});
        if (!Array.isArray(snap.apps)) throw Error('explorer_snapshot_failed');
        const explorers = snap.apps.filter(w => w.className === 'CabinetWClass' &&
          Number.isInteger(w.pid) && /^explorer$/i.test(w.process || '') && w.hwnd);
        const coveredPids = new Set(explorers.map(w => w.pid));
        all = all.filter(w => !/^explorer$/i.test(w.process) || !coveredPids.has(w.pid)).concat(explorers.map(w => ({pid: w.pid,
          process: w.process.slice(0, 100), ...(includeTitles ? {title: String(w.name || '').slice(0, MAX_TITLE)} : {})})));
      } catch {
        return {windows: all.slice(0, MAX_WINDOWS), count: all.length, truncated: all.length > MAX_WINDOWS,
          titles: includeTitles, partial: true, explorerInventory: 'unavailable'};
      }
    }
    return {windows: all.slice(0, MAX_WINDOWS), count: all.length, truncated: all.length > MAX_WINDOWS, titles: includeTitles};
  } finally {
    fs.rmSync(outFile, {force: true});
  }
}
