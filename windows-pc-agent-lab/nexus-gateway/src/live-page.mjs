/**
 * NEXUS 0.5.0 — external Live View page on the gateway (variant B; works when the ChatGPT client does not render the
 * widget). Phone/PC browser → https://<gateway>/live.
 *
 * Security:
 *  - Login with the OWNER PASSPHRASE through the same ConsentGuard Durable Object as OAuth consent: single-use nonce,
 *    shared brute-force lockout (5 fails → 15 min).
 *  - Session = cookie `__Host-nx_live` (HttpOnly; Secure; SameSite=Strict; Path=/; 30 min), payload signed with HMAC-SHA256.
 *    Key derived from NEXUS_TOKEN + LIVE_SESSION_EPOCH (no new secret; bump the epoch var to revoke all sessions).
 *    Nothing secret ever appears in a URL, the page, JavaScript or logs.
 *  - Frames: GET /live/frame → gateway calls the PC's app-only tool live_frame over the tunnel with NEXUS_TOKEN
 *    (server side) → image/jpeg, Cache-Control: no-store. The PC still requires capability live_view=true.
 *  - STOP: POST /live/stop with header X-Nexus-Live: 1 (CSRF: SameSite=Strict + custom header) → live_control stop.
 *  - Strict CSP with a per-response script nonce; frame-ancestors 'none'.
 *  - 0.6.1 owner approvals (FR-10): GET /live/consents lists what waits for the OWNER (payments, secrets, irreversible
 *    deletion, Windows security, lifting his ban); POST /live/decide {consentId, decision} (X-Nexus-Live: 1) → Host
 *    owner_decide. These Host names are not in the model catalog, so ChatGPT can never approve; only this
 *    passphrase session can. The Host refuses GUI input into a window titled «NEXUS Live View» (no clicking here).
 */
const enc = new TextEncoder();
/**
 * 0.6.1 fix (04.11): owner decisions are SIGNED here (Ed25519). The key pair is generated by the gateway itself on
 * first use and kept in OAUTH_KV (Cloudflare) — never on the PC; the Host fetches only the public key (GET /owner-pub)
 * and refuses unsigned owner_decide calls. Concurrent first use: last writer wins and everyone re-reads the stored pair.
 */
export async function ownerKey(env) {
  let rec = null; try { rec = JSON.parse(await env.OAUTH_KV.get('owner_sign') || 'null'); } catch { rec = null; }
  if (!rec?.pkcs8 || !rec?.x) {
    const kp = await crypto.subtle.generateKey({name: 'Ed25519'}, true, ['sign', 'verify']);
    const pkcs8 = b64u(await crypto.subtle.exportKey('pkcs8', kp.privateKey));
    const x = (await crypto.subtle.exportKey('jwk', kp.publicKey)).x;
    await env.OAUTH_KV.put('owner_sign', JSON.stringify({pkcs8, x, createdAt: new Date().toISOString()}));
    rec = JSON.parse(await env.OAUTH_KV.get('owner_sign'));
  }
  const der = Uint8Array.from(atob(rec.pkcs8.replace(/-/g, '+').replace(/_/g, '/') + '='.repeat((4 - rec.pkcs8.length % 4) % 4)), c => c.charCodeAt(0));
  return {x: rec.x, priv: await crypto.subtle.importKey('pkcs8', der, {name: 'Ed25519'}, false, ['sign'])};
}
export async function signDecision(env, {consentId, decision, ts}) {
  const k = await ownerKey(env);
  return b64u(await crypto.subtle.sign({name: 'Ed25519'}, k.priv, enc.encode(`nexus-owner-decide-v1|${consentId}|${decision}|${ts}`)));
}
